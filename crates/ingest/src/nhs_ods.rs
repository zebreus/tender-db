struct ChildrenTable {
    children: Vec<Child>,
    index: HashMap<&'static str, usize>,
    by_parent: HashMap<&'static str, Vec<&'static str>>,
}

fn children_table() -> &'static ChildrenTable {
    static CHILDREN: OnceLock<ChildrenTable> = OnceLock::new();
    CHILDREN.get_or_init(|| parse_children(CHILDREN_TSV))
}

/// The checked-in children TSV is frozen and its integrity is pinned by the tests, so a
/// malformed line is a build defect and panics. Rows come sorted by (child, start).
fn parse_children(tsv: &'static str) -> ChildrenTable {
    let mut children: Vec<Child> = Vec::new();
    for line in tsv.lines().filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let fields: Vec<&'static str> = line.split('\t').collect();
        let [code, status, rc, role, rel, parent, _parent_role, start, end, _legal_end, name] = fields[..] else {
            panic!("nhs-ods-children.tsv: a row without eleven fields: {line:?}");
        };
        if children.last().is_none_or(|c| c.code != code) {
            children.push(Child { code, name, role, active: status == "A", rc1: rc == "RC1", parents: Vec::new() });
        }
        if rel != "-" {
            let end = (!end.is_empty()).then_some(end);
            children.last_mut().expect("pushed above").parents.push(Parent { code: parent, rel, start, end });
        }
    }
    children.sort_by_key(|c| c.code);
    for c in &mut children {
        c.parents.sort_by_key(|p| (p.start, p.code));
    }
    let index = children.iter().enumerate().map(|(i, c)| (c.code, i)).collect();
    let mut by_parent: HashMap<&'static str, Vec<&'static str>> = HashMap::new();
    for c in &children {
        for p in &c.parents {
            let codes = by_parent.entry(p.code).or_default();
            if codes.last() != Some(&c.code) {
                codes.push(c.code);
            }
        }
    }
    ChildrenTable { children, index, by_parent }
}

struct Table {
    orgs: Vec<Org>,
    index: HashMap<&'static str, usize>,
    /// Each row's name, split once ([`Words`]), parallel to `orgs`.
    words: Vec<Words>,
}

fn table() -> &'static Table {
    static TABLE: OnceLock<Table> = OnceLock::new();
    TABLE.get_or_init(|| parse(TSV))
}

/// The checked-in TSV is frozen and its integrity is pinned by the tests, so a malformed
/// line is a build defect and panics.
fn parse(tsv: &'static str) -> Table {
    let mut orgs: Vec<Org> = Vec::new();
    for line in tsv.lines().filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let fields: Vec<&'static str> = line.split('\t').collect();
        let [code, status, rc, role, allow, predecessors, successors, legal_end, name] = fields[..] else {
            panic!("nhs-ods.tsv: a row without nine fields: {line:?}");
        };
        orgs.push(Org {
            code,
            name,
            active: status == "A",
            rc1: rc == "RC1",
            role: Role::from_id(role),
            allow: allow == "1",
            predecessors: predecessors.split(',').filter(|p| !p.is_empty()).collect(),
            successors: successors.split(',').filter(|p| !p.is_empty()).collect(),
            legal_end: (!legal_end.is_empty()).then_some(legal_end),
        });
    }
    orgs.sort_by_key(|o| o.code);
    let index = orgs.iter().enumerate().map(|(i, o)| (o.code, i)).collect();
    let words = orgs.iter().map(|o| Words::of_tokens(&tokens(o.name))).collect();
    Table { orgs, index, words }
}

/// The role a name declares by its words.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Declared {
    Trust,
    Icb,
    Csu,
}

/// B4's stop words: dropped before anything is compared.
const STOP: [&str; 16] =
    ["nhs", "the", "and", "of", "for", "in", "t", "as", "trading", "c", "o", "limited", "ltd", "plc", "at", "with"];

/// B4's descriptors: the NHS vocabulary every body shares, compared apart from the
/// distinctive words and only after them.
const DESCRIPTORS: [&str; 32] = [
    "hospital", "university", "teaching", "healthcare", "health", "care", "community", "mental", "partnership",
    "service", "ambulance", "children", "women", "specialist", "acute", "general", "foundation", "trust",
    "integrated", "board", "commissioning", "support", "unit", "clinical", "group", "strategic", "local", "sub",
    "location", "solution", "provider", "collaborative",
];

/// A name split into distinctive words and descriptors, each deduplicated, plus the role
/// its words declare.
struct Words {
    distinct: Vec<String>,
    descriptors: Vec<String>,
    declared: Option<Declared>,
}

impl Words {
    fn of_tokens(tokens: &[String]) -> Words {
        let mut words: Vec<String> = Vec::with_capacity(tokens.len());
        for t in tokens {
            if STOP.contains(&t.as_str()) {
                continue;
            }
            let w = if t.len() > 3 && t.ends_with('s') && !t.ends_with("ss") { &t[..t.len() - 1] } else { t.as_str() };
            words.push(w.to_string());
        }
        let has = |w: &str| words.iter().any(|x| x == w);
        let declared = if has("commissioning") && has("support") {
            Some(Declared::Csu)
        } else if (has("integrated") && has("board")) || (has("clinical") && has("commissioning")) {
            Some(Declared::Icb)
        } else if has("trust") {
            Some(Declared::Trust)
        } else {
            None
        };
        let (mut descriptors, mut distinct): (Vec<String>, Vec<String>) =
            words.into_iter().partition(|w| DESCRIPTORS.contains(&w.as_str()));
        for v in [&mut descriptors, &mut distinct] {
            v.sort_unstable();
            v.dedup();
        }
        Words { distinct, descriptors, declared }
    }
}

/// A name's fit to one ODS name, compared lexicographically: role agreement (0 or 1), then
/// the distinctive Jaccard, then the descriptor Jaccard.
#[derive(Debug, Clone, Copy, PartialEq, PartialOrd)]
struct Key {
    role: u8,
    distinct: f64,
    descriptor: f64,
}

impl Key {
    const NONE: Key = Key { role: 0, distinct: 0.0, descriptor: 0.0 };

    fn of(name: &Words, ods: &Words, role: Role) -> Key {
        let agrees = name.declared.is_none_or(|d| role.declared() == Some(d));
        Key {
            role: u8::from(agrees),
            distinct: prefix_jaccard(&name.distinct, &ods.distinct),
            descriptor: jaccard(&name.descriptors, &ods.descriptors),
        }
    }

    fn better(self, other: Key) -> Key {
        if other > self { other } else { self }
    }
}

/// Two distinctive words match when equal, or when both have 6 characters or more and one
/// is a prefix of the other (`cambridge` ~ `cambridgeshire`).
fn prefix_match(a: &str, b: &str) -> bool {
    a == b || (a.len().min(b.len()) >= 6 && (a.starts_with(b) || b.starts_with(a)))
}

/// B4's prefix-tolerant Jaccard: the name's words with a match in the ODS name, over the
/// union that count implies. Counted from the name's side, as the scripts do.
fn prefix_jaccard(name: &[String], ods: &[String]) -> f64 {
    if name.is_empty() || ods.is_empty() {
        return 0.0;
    }
    let m = name.iter().filter(|a| ods.iter().any(|b| prefix_match(a, b))).count();
    m as f64 / (name.len() + ods.len() - m) as f64
}

fn jaccard(a: &[String], b: &[String]) -> f64 {
    if a.is_empty() || b.is_empty() {
        return 0.0;
    }
    let both = a.iter().filter(|w| b.contains(w)).count();
    both as f64 / (a.len() + b.len() - both) as f64
}

/// A name's words before B4's stop list: lower case; `&` as ` and `; apostrophes dropped
/// (`King's` → `kings`); every other run outside `a-z0-9` a break; `n h s` as `nhs`; and
/// `icb`, `ccg`, `csu`, `ft`, `st` spelled out.
fn tokens(name: &str) -> Vec<String> {
    let mut folded = String::with_capacity(name.len() + 8);
    for c in name.chars() {
        match c {
            '&' => folded.push_str(" and "),
            '\'' | '\u{2019}' => {}
            c => {
                for l in c.to_lowercase() {
                    folded.push(if l.is_ascii_lowercase() || l.is_ascii_digit() { l } else { ' ' });
                }
            }
        }
    }
    let raw: Vec<&str> = folded.split(' ').filter(|t| !t.is_empty()).collect();
    let mut out: Vec<String> = Vec::with_capacity(raw.len() + 4);
    let mut i = 0;
    while i < raw.len() {
        if raw[i..].starts_with(&["n", "h", "s"]) {
            out.push("nhs".into());
            i += 3;
            continue;
        }
        match raw[i] {
            "icb" => out.extend(["integrated", "care", "board"].map(String::from)),
            "ccg" => out.extend(["clinical", "commissioning", "group"].map(String::from)),
            "csu" => out.extend(["commissioning", "support", "unit"].map(String::from)),
            "ft" => out.extend(["foundation", "trust"].map(String::from)),
            "st" => out.push("saint".into()),
            word => out.push(word.into()),
        }
        i += 1;
    }
    out
}

/// B4's agent markers, matched case-blind on the raw name at word boundaries.
fn agent(name: &str) -> bool {
    const MARKERS: [&str; 5] = ["c/o", "care of", "on behalf of", "acting for", "acting on behalf"];
    let lower = name.to_lowercase();
    let word = |c: char| c.is_alphanumeric() || c == '_';
    MARKERS.iter().any(|m| {
        lower.match_indices(m).any(|(at, _)| {
            !lower[..at].chars().next_back().is_some_and(word) && !lower[at + m.len()..].chars().next().is_some_and(word)
        })
    })
}

/// The judges' non-NHS graft over [`tokens`] (see [`check`], step 2).
fn non_nhs(tokens: &[String], company: bool) -> bool {
    let has = |w: &str| tokens.iter().any(|t| t == w);
    let any = |ws: &[&str]| ws.iter().any(|w| has(w));
    let nhs_role = any(&["nhs", "trust", "trusts", "commissioning"])
        || (has("integrated") && has("care") && any(&["board", "boards"]));
    if nhs_role {
        return false;
    }
    any(&["council", "councils", "school", "schools", "charity", "charities", "charitable"])
        || (any(&["university", "universities", "college", "colleges"]) && !any(&["hospital", "hospitals"]))
        || (!company && any(&["limited", "ltd", "plc", "llp"]))
}

