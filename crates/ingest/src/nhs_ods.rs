    /// The table holds no twin pair, so the ambiguity is exercised through the seam: with
    /// both `R0B` and `ROB` allowed, a third spelling cannot pick between them.
    #[test]
    fn a_fold_between_two_allowed_twins_is_ambiguous() {
        let twins = |code: &str| match code {
            "R0B" => Some("R0B"),
            "ROB" => Some("ROB"),
            _ => None,
        };
        assert_eq!(fold_unique("R0B", twins), Some(("R0B", false)), "an allowed tail is itself");
        assert_eq!(fold_unique("ROB", twins), Some(("ROB", false)));
        let one = |code: &str| (code == "R0B").then_some("R0B");
        assert_eq!(fold_unique("ROB", one), Some(("R0B", true)));
        // `O0B` folds to `00B` and to `OOB`; with both allowed, neither is chosen.
        let both = |code: &str| match code {
            "00B" => Some("00B"),
            "OOB" => Some("OOB"),
            _ => None,
        };
        assert_eq!(fold_unique("O0B", both), None, "two allowed variants are ambiguous");
    }

