    /// The check over every adjudicated holder of unit 1. Run with an ABSOLUTE rows path
    /// (cargo runs the test from `crates/ingest`) and the gate's flags and package set
    /// (CLAUDE.md): `NHS_ODS_ADJUDICATION_ROWS=/home/user/tender-db/.scratch/tender-db/
    /// 513-nhs/u1/adjudication-rows.json CARGO_INCREMENTAL=0 CARGO_PROFILE_DEV_DEBUG=0
    /// CARGO_PROFILE_TEST_DEBUG=0 cargo test -p model -p store -p ingest -p tender-db
    /// --features tender-db/server --lib nhs_ods_adjudication_tally -- --ignored --nocapture`,
    /// and `NHS_ODS_VERDICTS=<file>` to write one verdict line per row.
    #[test]
    #[ignore = "reads the scratch adjudication rows named by NHS_ODS_ADJUDICATION_ROWS"]
    fn nhs_ods_adjudication_tally() {
        use std::collections::BTreeMap;
        let path = std::env::var("NHS_ODS_ADJUDICATION_ROWS").expect("NHS_ODS_ADJUDICATION_ROWS");
        let rows: Vec<serde_json::Value> =
            serde_json::from_str(&std::fs::read_to_string(&path).expect("read the rows")).expect("a JSON array");
        let mut tally: BTreeMap<(String, String, String), usize> = BTreeMap::new();
        let mut lines = Vec::new();
        for r in &rows {
            let field = |k: &str| r[k].as_str().unwrap_or_default().to_string();
            let (side, code, fin, name) = (field("side"), field("code"), field("final"), field("name"));
            let verdict = if org(&code).is_none() {
                "not-in-table".to_string()
            } else {
                match check(&code, &name) {
                    NameCheck::Admitted => "Admitted".into(),
                    NameCheck::Tie { rival } => format!("Tie:{rival}"),
                    NameCheck::Refused(Refusal::Better { rival }) => format!("Refused:Better:{rival}"),
                    NameCheck::Refused(why) => format!("Refused:{why:?}"),
                }
            };
            let class = verdict.split(':').take(2).collect::<Vec<_>>().join(":");
            let class = if class.starts_with("Tie") { "Tie".to_string() } else { class };
            *tally.entry((side.clone(), fin.clone(), class)).or_default() += 1;
            if verdict != "not-in-table" {
                lines.push(format!("{side}\t{code}\t{fin}\t{verdict}\t{name}"));
            }
        }
        for ((side, fin, class), n) in &tally {
            println!("tally\t{side}\t{fin}\t{class}\t{n}");
        }
        if let Ok(out) = std::env::var("NHS_ODS_VERDICTS") {
            std::fs::write(out, lines.join("\n") + "\n").expect("write the verdicts");
        }
    }
