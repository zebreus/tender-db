//! Issue 513 U1: the frozen ODS table of NHS organisation codes, and the name check a
//! reviewed `nhs-body` verdict answers to (decision "unit 2, second", D3).
//!
//! A letter-only NHS code (`GB-NHS-RTH`) mints no identity: the digit rule, and for
//! `GB-NHS-R0B` the all-zero rule, refuse it in [`crate::project::normalise_identifier`].
//! The decision keeps it that way (D1: no mint). Each body's SAME clusters are folded by
//! a reviewed, ODS-confirmed, members-exact verdict instead. This module is the ODS half
//! of that review, and it is pure: the data is `sdk/nhs-ods.tsv`, read once. U1 changed no
//! behaviour. The dry census (U2, `store::Db::plan_nhs_bodies`) reads it through
//! [`census_code`] and [`census_check`], injected as fn pointers; the wet path (U4) will.
//!
//! **The table** (`sdk/nhs-ods.tsv`, version [`VERSION`]) is generated by
//! `.scratch/tender-db/513-nhs/u1-table/gen_nhs_ods_table.py` from the ODS ORD API on
//! 2026-10-11. It holds every organisation whose primary role is RO197 (NHS trust), RO107
//! (care trust), RO261 (strategic partnership: the ICBs, NHS England's regions,
//! networks), RO213 (CSU) or RO98 (CCG / sub-ICB location), in three and five characters
//! and any status. RO172 (independent-sector provider) is there only for the measured
//! code DQF. Every row is a RIVAL in the name check, so a name that fits a sub-ICB
//! location, a closed trust or a five-character network better than the code is caught.
//!
//! **The allowlist** ([`Org::allow`], design A's, 215 codes) decides who may be a
//! survivor. A code is on it when it is Active and RC1, has three characters with a tail in
//! the digit-rule family (letters only, or its only digits are 0), and its primary role is
//! RO197, RO107 or RO213, RO261 with a `Q` lead, or it is DQF. RO98 and Inactive codes
//! never are, so `00N`, `00P`, `ICB`, `TBC` and `NHS` cannot become a survivor
//! ([`survivor_code`]). A code ODS still answers Active stays on it even when its record
//! carries a legal end: 35 allowlisted codes do ([`Org::legal_end`], [`Org::successors`]).
//! Seven of them ended with the 2026-04 ICB mergers (`QJG QMJ QMM QNQ QXU RNK RYV`; `QHG
//! QNX QRV QUE` too), `TAF` and `RRP` in 2024 (successor `G6V2S`), and some long before
//! the GB-NHS scheme existed (`RBF` 2011, successor `RTH`). D6 keeps a successor's names
//! out of its predecessor's body, and the check enforces it because the successors are
//! rivals. The census (U2) flags a code published after its legal end.
//!
//! **The check** ([`check`]) is design B's "B4", ported from the panel's scripts
//! (`.scratch/tender-db/513-nhs/u2-panel/designB/b4.py`, `gate_b2.py`, `gate_b3.py`), plus
//! the judges' two grafts. It asks whether a head name belongs to the code, measured
//! against ODS. The code's names are its current ODS name plus the names of its Inactive
//! predecessors (RWW's `Warrington and Halton` spellings match RKC `Warrington Hospital`
//! and RJS `Halton General`). The rivals are every other row except those predecessors.
//! It is a PLANNER FLAG in design C, never a binding gate. A member the check refuses
//! needs a HIGH verdict citing ODS rename or predecessor evidence (D3), and nothing binds
//! on its answer.
//!
//! Measured over the 389 adjudicated holders (`.scratch/tender-db/513-nhs/u1/
//! adjudication-rows.json`, the `nhs_ods_adjudication_tally` test below), it admits 233 of
//! 235 SAME registry holders and 116 of 116 SAME PPON holders, and no DIFFERENT or NOT_ORG
//! holder on either side.
//!
//! **Issue 519 unit 2: the dated child map** (`sdk/nhs-ods-children.tsv`, version
//! [`CHILDREN_VERSION`], decision `.scratch/tender-db/519-nhs-digit-codes/unit2-decision.md`
//! §2). A CHILD code is an ODS code that ODS dates under a body's code: an RO98 sub-ICB
//! location under its RO261 ICB (relationship RE5; `B2M3M` under QWU, `13T` under QHM), or
//! a measured RO198 trust site under its RO197 trust (RE6; `RBT20` under RBT). Such a code
//! with a digit mints an identity of its own, so one body stands as several canonical orgs;
//! the census lists those holders under their parent, and a reviewed nhs-body verdict may
//! name them. The map is a SIBLING file: `nhs-ods.tsv`, [`VERSION`] and every 513 answer stay
//! byte for byte as they were. Parents are DATED ([`Parent`]), because the 2026-04 ICB
//! mergers moved them (`26A`: QMM to 2026-03-31, then T6Y0W). [`child_check`] is the strict
//! name gate a child's every name must pass under the parent (§1.3).

