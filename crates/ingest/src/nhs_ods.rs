/// An ODS primary role, as far as the check tells them apart.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Role {
    /// RO197, NHS TRUST.
    Trust,
    /// RO107, CARE TRUST (`TAD`, `TAJ`, …).
    CareTrust,
    /// RO261, STRATEGIC PARTNERSHIP: the ICBs, NHS England's regions and networks.
    Icb,
    /// RO213, COMMISSIONING SUPPORT UNIT.
    Csu,
    /// RO98, CLINICAL COMMISSIONING GROUP: the CCGs and today's sub-ICB locations
    /// (`00N`, `06H`). Rivals only, never allowlisted (issue 519's).
    SubIcb,
    /// RO172, INDEPENDENT SECTOR HEALTHCARE PROVIDER (DQF only).
    IsProvider,
    /// Any other role id. The generator writes none; kept so a regenerated table with a
    /// new role parses rather than panics.
    Other(&'static str),
}

impl Role {
    fn from_id(id: &'static str) -> Role {
        match id {
            "RO197" => Role::Trust,
            "RO107" => Role::CareTrust,
            "RO261" => Role::Icb,
            "RO213" => Role::Csu,
            "RO98" => Role::SubIcb,
            "RO172" => Role::IsProvider,
            other => Role::Other(other),
        }
    }

    /// The ODS role id (`RO197`).
    pub fn id(self) -> &'static str {
        match self {
            Role::Trust => "RO197",
            Role::CareTrust => "RO107",
            Role::Icb => "RO261",
            Role::Csu => "RO213",
            Role::SubIcb => "RO98",
            Role::IsProvider => "RO172",
            Role::Other(id) => id,
        }
    }

    /// The role a name could declare for a code of this role. A company or an unknown
    /// role declares none, so a name that declares a role never fits it.
    fn declared(self) -> Option<Declared> {
        match self {
            Role::Trust | Role::CareTrust => Some(Declared::Trust),
            Role::Icb | Role::SubIcb => Some(Declared::Icb),
            Role::Csu => Some(Declared::Csu),
            Role::IsProvider | Role::Other(_) => None,
        }
    }
}

/// One row of the table.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Org {
    /// The ODS code, three or five characters (`RTH`, `8HN02`).
    pub code: &'static str,
    /// The ODS name, as ODS writes it (upper case).
    pub name: &'static str,
    /// ODS status Active (else Inactive).
    pub active: bool,
    /// Record class RC1, an organisation rather than a site.
    pub rc1: bool,
    /// The primary role.
    pub role: Role,
    /// On the survivor allowlist (module doc).
    pub allow: bool,
    /// The code's Inactive predecessors from its ORD record. Recorded for allowlisted rows
    /// only; each one is a row of the table.
    pub predecessors: Vec<&'static str>,
    /// The code's successors from its ORD record, in the table or not (`TAF` → `G6V2S`).
    /// Recorded for allowlisted rows only.
    pub successors: Vec<&'static str>,
    /// The end of the code's legal period (`YYYY-MM-DD`) when its ORD record has one, even
    /// though ODS still answers it Active. Recorded for allowlisted rows only.
    pub legal_end: Option<&'static str>,
}

/// The row for an ODS code, any role or status, or `None` when the table has no such code.
pub fn org(code: &str) -> Option<&'static Org> {
    let t = table();
    t.index.get(code).map(|&i| &t.orgs[i])
}

/// Every row, in code order.
pub fn orgs() -> &'static [Org] {
    &table().orgs
}

/// The three-character tail of a normalised NHS identifier value: `GBNHSRTH` → `RTH`.
///
/// The value is what [`crate::project::normalise_identifier`]'s filter leaves (ASCII
/// letters and digits, upper case), whether or not that function then mints it. Exactly
/// `GBNHS` and three characters; a typed name (`GBNHSNHSCHESHIREANDMERSEYSIDEICB`), a
/// five-character code (`GBNHS8HN02`) and anything not normalised come back `None`.
pub fn nhs_tail(value: &str) -> Option<&str> {
    let tail = value.strip_prefix("GBNHS")?;
    let normalised = value.bytes().all(|b| b.is_ascii_uppercase() || b.is_ascii_digit());
    (tail.len() == 3 && normalised).then_some(tail)
}

/// The allowlisted code a tail names, and whether an O↔0 fold was needed to reach it.
///
/// A tail on the allowlist is its own code (`RTH` → `(RTH, false)`). Otherwise, if
/// exactly one variant with some of its `O`s and `0`s swapped is allowlisted, that one
/// (`ROB` → `(R0B, true)`, `Q0X` → `(QOX, true)`). No O/0 twin pair exists anywhere in the
/// table (a test pins it), so the fold cannot pick between two real codes. Anything else
/// is `None`: RO98 codes (`00N`), Inactive ones (`RCN`, `RMB`), non-allowlisted roles, and
/// codes ODS does not know (`ICB`, `TBC`, `NHS`, `OYG`, `RGY`).
pub fn survivor_code(tail: &str) -> Option<(&'static str, bool)> {
    if tail.len() != 3 || !tail.bytes().all(|b| b.is_ascii_uppercase() || b.is_ascii_digit()) {
        return None;
    }
    fold_unique(tail, |code| org(code).filter(|o| o.allow).map(|o| o.code))
}

/// [`survivor_code`]'s choice over an `allowed` predicate: the tail itself, else its one
/// allowed O↔0 variant. Two different allowed variants are ambiguous and give `None`. The
/// frozen table holds no twin pair, so that branch is reachable only through this seam
/// (the test injects one).
fn fold_unique(tail: &str, allowed: impl Fn(&str) -> Option<&'static str>) -> Option<(&'static str, bool)> {
    if let Some(code) = allowed(tail) {
        return Some((code, false));
    }
    let mut hit = None;
    for variant in o0_variants(tail) {
        if let Some(code) = allowed(&variant) {
            if hit.is_some_and(|h| h != code) {
                return None;
            }
            hit = Some(code);
        }
    }
    hit.map(|code| (code, true))
}

/// Every spelling of an ASCII code with a non-empty subset of its `O`s and `0`s swapped
/// (`ROB` → `R0B`; `O0X` → `00X`, `OOX`, `0OX`).
fn o0_variants(code: &str) -> Vec<String> {
    let bytes = code.as_bytes();
    let swaps: Vec<usize> = (0..bytes.len()).filter(|&i| matches!(bytes[i], b'O' | b'0')).collect();
    (1..(1u32 << swaps.len()))
        .map(|mask| {
            let mut variant = bytes.to_vec();
            for (k, &i) in swaps.iter().enumerate() {
                if mask >> k & 1 == 1 {
                    variant[i] = if variant[i] == b'O' { b'0' } else { b'O' };
                }
            }
            String::from_utf8(variant).expect("ASCII in, ASCII out")
        })
        .collect()
}

/// The answer of [`check`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NameCheck {
    /// The name passes every test and fits the code strictly better than every rival.
    Admitted,
    /// The name passes every test, but a rival fits it exactly as well (the first such
    /// rival in code order). Not admitted silently: the judges' graft.
    Tie { rival: &'static str },
    Refused(Refusal),
}

/// Why [`check`] refused a name.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Refusal {
    /// The name carries an agent marker (`c/o`, `care of`, `on behalf of`, `acting for`,
    /// `acting on behalf`): another party's name rides on the body's.
    Agent,
    /// A university, council, school, charity or company name with no NHS role token
    /// (`University of Oxford` under RTH). The judges' graft.
    NonNhs,
    /// The name declares a role (trust, ICB, CSU) that none of the code's names has.
    Role,
    /// The name shares no distinctive word with any of the code's names.
    Zero,
    /// A rival fits the name strictly better (the first best rival in code order).
    Better { rival: &'static str },
    /// The code's best name covers less than half of the name's distinctive words.
    Coverage,
    /// The code is not in the table.
    Unknown,
    /// Issue 519 unit 2, [`child_check`] only: the name carries the word `england` and
    /// declares no ICB, trust or CSU role — NHS England (`NHS England North East and
    /// Yorkshire`), whose regions (RO209/RO210) are not in the table to be a rival.
    Nhse,
}

/// Whether `head_name` belongs to the ODS `code` (see the module doc).
///
/// The tests run in this order, and the first that fails answers:
/// 1. **Agent**: an agent marker in the raw name.
/// 2. **NonNhs**: a university, council, school, charity or legal-form word (`limited`,
///    `ltd`, `plc`, `llp`) with no NHS role token (`nhs`, `trust`, `commissioning`,
///    `integrated care board`; `icb`, `ccg` and `csu` are spelled out first).
///    `university` and `college` yield to `hospital`, the trust naming of `University
///    Hospitals Birmingham` and `King's College Hospital`; a hospital charity (`University
///    Hospitals Birmingham Charity`) is a separate registered body and stays refused. A
///    company code's own legal form (`… Solutions Limited`, DQF) is no marker.
/// 3. The name's words, after B4's fold: lower case, `&` as `and`, `icb`, `ccg`, `csu`,
///    `ft`, `n h s` and `st` spelled out, the stop words dropped, and a plural `s` cut. Each
///    word is a descriptor (`hospital`, `trust`, `community`, …) or distinctive
///    (`Warrington`, `Devon`). Two distinctive words of 6 characters or more match when one
///    is a prefix of the other (`cambridge` ~ `cambridgeshire`). A name's key against one
///    ODS name is (role agreement, distinctive Jaccard, descriptor Jaccard), compared in
///    that order. The code's key is its best over its own names. **Role**: the name declares
///    a role that no own name has. **Zero**: the key's distinctive share is 0.
/// 4. **Better**: a rival's key is strictly greater.
/// 5. **Coverage**: the code's best own name covers fewer than half of the name's
///    distinctive words (`Northumbria Healthcare Facilities Management` under RTF).
/// 6. **Tie**: a rival's key is exactly equal.
///
/// Deterministic: the rivals are walked in code order, and the first best one is named.
pub fn check(code: &str, head_name: &str) -> NameCheck {
    gate(code, head_name, false)
}

/// Issue 519 unit 2 (decision §1.3): the strict name gate of a CHILD code's names under
/// its dated `parent` — [`check`] with two changes, and the same fn gates the bind (U4), so
/// prevention is never looser than the reviewed merge.
///
/// 1. **Rivals**: every row except the parent's own names (the parent and its Inactive
///    predecessors, as in [`check`]) and except the **relabel** rows: an Active RO98 row
///    NAMED "<current ICB> - <code>" (`NHS COVENTRY AND WARWICKSHIRE ICB - B2M3M`; 107 rows
///    since 2026-04). Such a row duplicates its ICB's row and declares the ICB role, so under
///    [`check`] it beats the ICB for any name that carries the code. Only the name shape
///    marks one: the other 58 Active RO98 rows are bodies of their own and stay rivals —
///    NHS England's commissioning hubs (`13X CUMBRIA AND NORTH EAST COMMISSIONING HUB`, which
///    must keep beating QHM for a hub-named mention), the legacy CCGs `00W`, `12A` and `13P`,
///    and London's "<borough> - SUB-ICB REPORTING ENTITY" rows (narrowed after the unit 2
///    review). Inactive RO98 rows (abolished CCGs) stay rivals.
/// 2. **Nhse** ([`Refusal::Nhse`]): a name with the token `england` that declares no ICB,
///    trust or CSU role is refused, after NonNhs and before Role.
///
/// Only [`NameCheck::Admitted`] passes: a `Tie` refuses.
pub fn child_check(parent: &str, name: &str) -> NameCheck {
    gate(parent, name, true)
}

/// Issue 519 unit 2 (decision §1.3): whether `o` is a RELABEL row, the rows [`child_check`]
/// drops from its rivals — an Active RO98 row whose ODS name is "<current ICB> - <its own
/// code>" (`NHS NORFOLK AND SUFFOLK ICB - 26A`). A hub, a legacy CCG or a London reporting
/// entity is Active RO98 too, but named as itself, and is no relabel.
fn relabel(o: &Org) -> bool {
    o.role == Role::SubIcb && o.active && o.name.strip_suffix(o.code).is_some_and(|n| n.ends_with(" - "))
}

/// [`check`] (`child: false`) and [`child_check`] (`child: true`): one walk, so the two
/// answer alike wherever 519's two changes do not apply.
fn gate(code: &str, head_name: &str, child: bool) -> NameCheck {
    let t = table();
    let Some(&at) = t.index.get(code) else {
        return NameCheck::Refused(Refusal::Unknown);
    };
    let org = &t.orgs[at];
    if agent(head_name) {
        return NameCheck::Refused(Refusal::Agent);
    }
    let toks = tokens(head_name);
    if non_nhs(&toks, org.role == Role::IsProvider) {
        return NameCheck::Refused(Refusal::NonNhs);
    }
    let name = Words::of_tokens(&toks);
    if child && name.declared.is_none() && toks.iter().any(|t| t == "england") {
        return NameCheck::Refused(Refusal::Nhse);
    }
    let own: Vec<usize> =
        std::iter::once(at).chain(org.predecessors.iter().filter_map(|p| t.index.get(p).copied())).collect();
    let own_key = own.iter().map(|&i| Key::of(&name, &t.words[i], t.orgs[i].role)).fold(Key::NONE, Key::better);
    if own_key.role == 0 {
        return NameCheck::Refused(Refusal::Role);
    }
    if own_key.distinct == 0.0 {
        return NameCheck::Refused(Refusal::Zero);
    }
    let mut best: Option<(Key, &'static str)> = None;
    for (i, rival) in t.orgs.iter().enumerate() {
        if own.contains(&i) {
            continue;
        }
        // 519 §1.3: a relabel row duplicates its current ICB's row under a code.
        if child && relabel(rival) {
            continue;
        }
        let key = Key::of(&name, &t.words[i], rival.role);
        if best.is_none_or(|(b, _)| key > b) {
            best = Some((key, rival.code));
        }
    }
    if let Some((key, rival)) = best
        && key > own_key
    {
        return NameCheck::Refused(Refusal::Better { rival });
    }
    let covered = own
        .iter()
        .map(|&i| name.distinct.iter().filter(|a| t.words[i].distinct.iter().any(|b| prefix_match(a, b))).count())
        .max()
        .unwrap_or(0);
    if 2 * covered < name.distinct.len() {
        return NameCheck::Refused(Refusal::Coverage);
    }
    if let Some((key, rival)) = best
        && key == own_key
    {
        return NameCheck::Tie { rival };
    }
    NameCheck::Admitted
}

/// Issue 513 U2: a row as the store's nhs-body census reads it ([`store::NhsOdsCode`]).
/// Injected as `NhsBodyArgs::ods`: store never depends on ingest, so the census takes this
/// table through a plain fn, the way it takes the crosswalk's keys.
pub fn census_code(code: &str) -> Option<store::NhsOdsCode> {
    org(code).map(|o| store::NhsOdsCode {
        code: o.code,
        name: o.name,
        role: o.role.id(),
        active: o.active,
        allow: o.allow,
        predecessors: o.predecessors.clone(),
        successors: o.successors.clone(),
        legal_end: o.legal_end,
    })
}

/// Issue 513 U2: [`check`] flattened for the census's report (`NhsBodyArgs::check`): the
/// answer as a label, and the rival a tie or a `better` refusal names.
pub fn census_check(code: &str, head_name: &str) -> store::NhsNameCheck {
    census_label(check(code, head_name))
}

/// An answer of [`check`] or [`child_check`] as the census's label and rival.
fn census_label(answer: NameCheck) -> store::NhsNameCheck {
    let (verdict, rival) = match answer {
        NameCheck::Admitted => ("admitted", None),
        NameCheck::Tie { rival } => ("tie", Some(rival)),
        NameCheck::Refused(Refusal::Agent) => ("agent", None),
        NameCheck::Refused(Refusal::NonNhs) => ("non-nhs", None),
        NameCheck::Refused(Refusal::Role) => ("role", None),
        NameCheck::Refused(Refusal::Zero) => ("zero", None),
        NameCheck::Refused(Refusal::Better { rival }) => ("better", Some(rival)),
        NameCheck::Refused(Refusal::Coverage) => ("coverage", None),
        NameCheck::Refused(Refusal::Unknown) => ("unknown", None),
        NameCheck::Refused(Refusal::Nhse) => ("nhse", None),
    };
    store::NhsNameCheck { verdict, rival }
}

