# Generates judge2b.py from classes_tail.txt / classes_2b.txt (one line per kept row, in file order:
# "<index> <class> [note]"), keying each class by (org, name) as judge2a.py does.
import json
def load(cls_file, rows):
    out = {}
    lines = open(cls_file).read().strip().split('\n')
    assert len(lines) == len(rows)
    for i, (ln, r) in enumerate(zip(lines, rows)):
        parts = ln.split(' ', 2); assert int(parts[0]) == i
        c = parts[1]; note = parts[2] if len(parts) > 2 else ''
        assert c in ('V','U','A','T','C','F','F?'), ln
        k = (r['org'], r['name'])
        if k in out: assert out[k][0] == c, (k, out[k], c)
        out[k] = (c, note)
    return out
tail = [r for r in json.load(open('tail_k6.json')) if r['keep'] and r['detector'] not in ('STRAY', 'HELD-2')]
b = [r for r in json.load(open('cand2b.json')) if r['keep']]
JT = load('classes_tail.txt', tail); JB = load('classes_2b.txt', b)
def emit(name, J):
    s = name + ' = {\n'
    for (org, nm), (c, note) in J.items():
        s += f" ({org}, {nm!r}): {c!r},{'  # ' + note if note else ''}\n"
    return s + '}\n'
