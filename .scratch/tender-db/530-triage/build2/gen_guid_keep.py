#!/usr/bin/env python3
"""Issue 530 Build 2: write crates/ingest/sdk/guid-keep-530.tsv, the frozen KEEP_530, from the dry plan
report of queue job 2660 (`530-triage/guid_twin_plan_2660.json`, `body.keep_candidates`).

Usage (from the repo root): python3 -I .scratch/tender-db/530-triage/build2/gen_guid_keep.py \
    .scratch/tender-db/530-triage/guid_twin_plan_2660.json crates/ingest/sdk/guid-keep-530.tsv

The report's `body` is a JSON string (the stored report), so it is decoded twice. The script asserts
the decision's counts (7,312 distinct values, none with a NULL country, the reasons job 2660 printed)
and writes the rows sorted by value, a NULL field empty."""
import json
import re
import sys

VERSION = "keep-530-job2660"
EXPECT = {"multi_tender": 6967, "stable+multi_tender": 332, "stable": 13}


def main(src: str, dst: str) -> None:
    with open(src, encoding="utf-8") as f:
        report = json.load(f)
    assert report["kind"] == "guid-twin-plan", report["kind"]
    body = json.loads(report["body"])
    rows = body["keep_candidates"]
    assert body["max_id"] == 31_970_152, body["max_id"]
    assert body["stable_ids"] == [254, 255, 8378] and body["stable_mentions"] == 100
    assert len(rows) == 7312, len(rows)
    values = [r["value"] for r in rows]
    assert len(set(values)) == len(values), "distinct values"
    assert all(re.fullmatch(r"[0-9A-F]{32}", v) for v in values), "the GuidKeep key form"
    assert all(r["country"] for r in rows), "no NULL country"
    reasons = {}
    for r in rows:
        reasons[r["reason"]] = reasons.get(r["reason"], 0) + 1
    assert reasons == EXPECT, reasons
    rows.sort(key=lambda r: r["value"])

    def cell(v):
        return "" if v is None else str(v)

    out = [
        "# guid-keep-530.tsv: KEEP_530, the frozen value-keyed keep-list of issue 530 (rule 530-T).",
        f"# version: {VERSION}",
        "# Generated by .scratch/tender-db/530-triage/build2/gen_guid_keep.py; do not edit by hand.",
        "# source: queue job 2660 (dissolve-guid-twins, dry, binary 8e9222c, 2026-10-19), the stored report",
        "#   guid-twin-plan, body.keep_candidates (530-triage/guid_twin_plan_2660.json).",
        "# definition (530-triage/decision.md, KEEP_530, A3 ii): every uuid_v4 GUID row spanning >= 2 distinct",
        "#   Tenders (multi_tender), the stable rows (254, 255, 8378 and every uuid_v4 row with >= 100 mentions:",
        "#   stable) and every uuid_v4 value in organization_merged_identifiers (merged; 0 at job 2660), over",
        "#   org ids <= 31,970,152.",
        "# key form: store::GuidKeep::key, the value's ASCII letters and digits upper-cased (undashed); the",
        "#   lookup ignores the country column (A4).",
        "# columns: country, value, org_id (the GUID row at freeze), mentions, tenders, reason (stable,",
        "#   multi_tender, merged, joined by +); an empty cell is NULL.",
        "# changes: values are only ever ADDED (rows kept in value order), by a reviewed commit that adds what",
        "#   the dissolve-guid-twins recurrence arm or a dry re-plan's keep_add_commit lists; never removed.",
        f"# counts: {len(rows)} values: multi_tender {EXPECT['multi_tender']}, stable+multi_tender "
        f"{EXPECT['stable+multi_tender']}, stable {EXPECT['stable']}, merged 0.",
    ]
    for r in rows:
        out.append("\t".join(cell(r[k]) for k in ("country", "value", "org_id", "mentions", "tenders", "reason")))
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {len(rows)} rows to {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
