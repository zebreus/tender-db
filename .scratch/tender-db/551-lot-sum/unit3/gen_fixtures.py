def lit(s):
    if s is None:
        return "None"
    s = str(s)
    assert all(32 <= ord(c) < 127 for c in s), s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def opt(s):
    return "None" if s is None else f"Some({lit(s)})"


def opt_i(x):
    return "None" if x is None else f"Some({x})"


def amounts(facts, ind=None):
    items = [f"({lit(f.field)}, {f.cents}, {lit(f.currency)}, {opt(f.quality)})" for f in facts]
    if ind is None or len(items) <= 2:
        return "&[" + ", ".join(items) + "]"
    return "&[" + "".join(f"\n{ind}    {x}," for x in items) + f"\n{ind}]"


def version(v):
    ind = " " * 16
    lots = "&[" + "".join(f"\n{ind}    ({lit(l.key)}, {lit(l.kind)}, {amounts(l.facts)})," for l in v.lots) + (f"\n{ind}]" if v.lots else "]")
    rounds = "&[" + "".join(
        f"\n{ind}    ({r.notice_id}, &[" + "".join(
            f"\n{ind}        ({lit(x.key if x.key is not None else 'RES')}, {opt(x.lot_key)}, {opt_i(x.cents)}, {opt(x.currency)}),"
            for x in r.lot_results) + f"\n{ind}    ]),"
        for r in v.rounds) + (f"\n{ind}]" if v.rounds else "]")
    return f"V {{\n{ind}facts: {amounts(v.facts, ind)},\n{ind}lots: {lots},\n{ind}rounds: {rounds},\n            }}"


def api_versions(tid, path):
    d = json.load(open(path))
    lots = [{"lot_id": i, "kind": l["kind"], "lot_key": l["lot_key"]} for i, l in enumerate(d["lot_details"])]
    key_id = {l["lot_key"]: l["lot_id"] for l in lots}
    am, res = [], []
    for a in d["amounts"]:
        if a["value"] is None:
            continue
        am.append({"lot_id": None if a["lot"] is None else key_id[a["lot"]], "field": a["field"],
                   "cents": a["value"]["cents"], "currency": a["value"]["currency"], "tax_basis": None,
                   "eur_cents": a["value"]["cents"] if a["value"]["currency"] == "EUR" else None, "quality": None})
    for i, r in enumerate(d["lot_results"]):
        aw = r.get("awarded") or {}
        res.append({"lot_result_id": i, "lot_id": None if r["lot"] is None else key_id.get(r["lot"]),
                    "awarded_cents": aw.get("cents"), "awarded_currency": aw.get("currency"),
                    "notice_id": r["notice_id"], "result_key": r["key"]})
    keys = {l["lot_id"]: l["lot_key"] for l in lots}
    head = E.version_from_rows(am, [{"lot_id": l["lot_id"], "kind": l["kind"]} for l in lots], res, keys)
    chain = []
    if tid == 928196:
        # The 492 refusal names a x100 partner, EUR 46,797,460.35; the API dump holds the head version only,
        # so the partner's version (the first CN, 00217171-2026) is restated with that one procedure figure.
        chain.append(E.version_from_rows([{"lot_id": None, "field": "estimated_value", "cents": 4679746035,
                                           "currency": "EUR", "tax_basis": None, "eur_cents": 4679746035,
                                           "quality": None}], [], [], {}))
    return chain + [head], API_RATES.get(tid, {})


